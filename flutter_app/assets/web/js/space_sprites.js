  // --- Fast Pixel Matrix Drawing Utility ---
  drawSprite(ctx, matrix, x, y, scale = 2, palette, flipH = false) {
    if (!matrix || !matrix.length) return;
    const rows = matrix.length;
    const cols = matrix[0].length;
    const startX = Math.floor(x - (cols * scale) / 2);
    const startY = Math.floor(y - (rows * scale) / 2);

    for (let r = 0; r < rows; r++) {
      for (let c = 0; c < cols; c++) {
        const colIdx = flipH ? (cols - 1 - c) : c;
        const colorKey = matrix[r][colIdx];
        if (colorKey !== 0 && palette[colorKey]) {
          ctx.fillStyle = palette[colorKey];
          ctx.fillRect(startX + c * scale, startY + r * scale, scale, scale);
        }
      }
    }
  }
